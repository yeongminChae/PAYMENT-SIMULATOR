-- =====================================================================
-- schema-postgres.sql
-- PostgreSQL draft schema for the payment simulator.
--
-- This file intentionally does not replace db/schema.sql.
-- Date/time columns use TIMESTAMP because Java insert DTOs bind
-- LocalDateTime and current read models do not expose these columns.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) POS_TRX_SEQUENCE
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS POS_TRX_SEQUENCE
(
    SEQ_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STORE_CD   TEXT      NOT NULL,
    BIZ_DATE   TEXT      NOT NULL,
    POS_NO     TEXT      NOT NULL,
    SEQ        INTEGER   NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (STORE_CD, BIZ_DATE, POS_NO)
);

-- ---------------------------------------------------------------------
-- 2) PAYMENT_ATTEMPT_SEQ
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_ATTEMPT_SEQ
(
    SEQ_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POS_TRX    TEXT      NOT NULL,
    LAST_SEQ   INTEGER   NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (POS_TRX)
);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_ATTEMPT_SEQ_POS_TRX
    ON PAYMENT_ATTEMPT_SEQ (POS_TRX);

-- ---------------------------------------------------------------------
-- 3) PAYMENT_ATTEMPT
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_ATTEMPT
(
    ATTEMPT_ID       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POS_TRX          TEXT      NOT NULL,
    ATTEMPT_SEQ      INTEGER   NOT NULL,
    AMOUNT           INTEGER   NOT NULL,
    CARD_BIN         TEXT      NULL,
    CARD_LAST4       TEXT      NULL,
    CARD_FINGERPRINT TEXT      NULL,
    CARD_BRAND       TEXT      NULL,
    FINAL_STATUS     TEXT      NULL,
    APPROVAL_NO      TEXT      NULL,
    DECLINE_CODE     TEXT      NULL,
    VAN_TRX_ID       TEXT      NULL,
    CREATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (POS_TRX, ATTEMPT_SEQ),
    CHECK (AMOUNT > 0),
    CHECK (FINAL_STATUS IS NULL OR FINAL_STATUS IN ('APPROVED', 'DECLINED', 'UNKNOWN_TIMEOUT'))
);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_ATTEMPT_POS_TRX
    ON PAYMENT_ATTEMPT (POS_TRX);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_ATTEMPT_FINAL_STATUS
    ON PAYMENT_ATTEMPT (FINAL_STATUS);

-- ---------------------------------------------------------------------
-- 4) PAYMENT_CANCEL
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_CANCEL
(
    CANCEL_ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CURRENT_TRX_NO       TEXT      NOT NULL,
    ORIGINAL_TRX_NO      TEXT      NOT NULL,
    ORIGINAL_ATTEMPT_SEQ INTEGER   NOT NULL,
    CANCEL_STATUS        TEXT      NOT NULL,
    VAN_CANCEL_TRX_ID    TEXT,
    CANCEL_APPROVAL_NO   TEXT,
    DECLINE_CODE         TEXT,
    CREATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (CURRENT_TRX_NO),
    UNIQUE (ORIGINAL_TRX_NO, ORIGINAL_ATTEMPT_SEQ),

    FOREIGN KEY (ORIGINAL_TRX_NO, ORIGINAL_ATTEMPT_SEQ)
        REFERENCES PAYMENT_ATTEMPT (POS_TRX, ATTEMPT_SEQ)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    -- UNKNOWN_TIMEOUT은 VAN timeout으로 외부 취소 처리 여부를 단정할 수 없는 미확정 상태다.
    CHECK (CANCEL_STATUS IN ('PENDING', 'CANCELLED', 'CANCEL_DECLINED', 'UNKNOWN_TIMEOUT'))
);

ALTER TABLE PAYMENT_CANCEL
    ADD COLUMN IF NOT EXISTS VAN_CANCEL_TRX_ID TEXT;

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_CANCEL_STATUS
    ON PAYMENT_CANCEL (CANCEL_STATUS);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_CANCEL_ORIGINAL_TRX
    ON PAYMENT_CANCEL (ORIGINAL_TRX_NO);

-- ---------------------------------------------------------------------
-- 5) PAYMENT_REVERSAL
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_REVERSAL
(
    REVERSAL_ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CURRENT_TRX_NO       TEXT      NOT NULL,
    ORIGINAL_TRX_NO      TEXT      NOT NULL,
    ORIGINAL_ATTEMPT_SEQ INTEGER   NOT NULL,
    AMOUNT               INTEGER   NOT NULL,
    REVERSAL_STATUS      TEXT      NOT NULL,
    VAN_REVERSAL_TRX_ID  TEXT,
    REVERSAL_APPROVAL_NO TEXT,
    DECLINE_CODE         TEXT,
    CREATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (CURRENT_TRX_NO),
    UNIQUE (ORIGINAL_TRX_NO, ORIGINAL_ATTEMPT_SEQ),

    FOREIGN KEY (ORIGINAL_TRX_NO, ORIGINAL_ATTEMPT_SEQ)
        REFERENCES PAYMENT_ATTEMPT (POS_TRX, ATTEMPT_SEQ)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CHECK (AMOUNT > 0),
    CHECK (REVERSAL_STATUS IN ('PENDING', 'REVERSED', 'REVERSAL_DECLINED'))
);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_REVERSAL_STATUS
    ON PAYMENT_REVERSAL (REVERSAL_STATUS);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_REVERSAL_ORIGINAL_TRX
    ON PAYMENT_REVERSAL (ORIGINAL_TRX_NO);

-- ---------------------------------------------------------------------
-- 6) BIN_CATALOG
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BIN_CATALOG
(
    BIN        TEXT      NOT NULL,
    BRAND      TEXT      NULL,
    ISSUER     TEXT      NULL,
    COUNTRY    TEXT      NULL,
    BIN_LEN    INTEGER   NOT NULL,
    ACTIVE_YN  TEXT      NOT NULL DEFAULT 'Y',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (BIN),
    CHECK (ACTIVE_YN IN ('Y', 'N'))
);

CREATE INDEX IF NOT EXISTS IDX_BIN_CATALOG_ACTIVE
    ON BIN_CATALOG (ACTIVE_YN);

-- ---------------------------------------------------------------------
-- 7) PAYMENT_EXTERNAL_INFO
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_EXTERNAL_INFO
(
    EXTERNAL_INFO_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POS_TRX          TEXT      NOT NULL,
    ATTEMPT_SEQ      INTEGER   NOT NULL,
    CARD_BIN         TEXT      NOT NULL,
    CARD_LAST4       TEXT      NOT NULL,
    MASKED_CARD_NO   TEXT      NOT NULL,
    CARD_BRAND       TEXT      NOT NULL,
    CARD_ISSUER      TEXT      NOT NULL,
    CARD_COUNTRY     TEXT      NOT NULL,
    VAN_PROVIDER     TEXT      NOT NULL,
    CREATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (POS_TRX, ATTEMPT_SEQ),
    FOREIGN KEY (POS_TRX, ATTEMPT_SEQ)
        REFERENCES PAYMENT_ATTEMPT (POS_TRX, ATTEMPT_SEQ)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS IDX_PAYMENT_EXTERNAL_INFO_POS_TRX
    ON PAYMENT_EXTERNAL_INFO (POS_TRX);

-- ---------------------------------------------------------------------
-- 8) PAYMENT_EVENT_LOG
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_EVENT_LOG
(
    EVENT_ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVENT_TIME           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    EVENT_TYPE           TEXT      NOT NULL,
    POS_TRX              TEXT      NULL,
    ATTEMPT_SEQ          INTEGER   NULL,
    CURRENT_TRX_NO       TEXT      NULL,
    ORIGINAL_POS_TRX     TEXT      NULL,
    ORIGINAL_ATTEMPT_SEQ INTEGER   NULL,
    RESULT_CODE          TEXT      NULL,
    STATUS_SNAPSHOT      TEXT      NULL,
    VAN_TRX_ID           TEXT      NULL,
    APPROVAL_NO          TEXT      NULL,
    DECLINE_CODE         TEXT      NULL,
    CORRELATION_ID       TEXT      NULL,
    NOTE                 TEXT      NULL
);

CREATE INDEX IF NOT EXISTS IDX_EVENT_LOG_POS_TRX_ATTEMPT
    ON PAYMENT_EVENT_LOG (POS_TRX, ATTEMPT_SEQ);

CREATE INDEX IF NOT EXISTS IDX_EVENT_LOG_ORIGINAL
    ON PAYMENT_EVENT_LOG (ORIGINAL_POS_TRX, ORIGINAL_ATTEMPT_SEQ);

CREATE INDEX IF NOT EXISTS IDX_EVENT_LOG_CORRELATION
    ON PAYMENT_EVENT_LOG (CORRELATION_ID);

CREATE INDEX IF NOT EXISTS IDX_EVENT_LOG_EVENT_TYPE
    ON PAYMENT_EVENT_LOG (EVENT_TYPE);

CREATE INDEX IF NOT EXISTS IDX_EVENT_LOG_EVENT_TIME
    ON PAYMENT_EVENT_LOG (EVENT_TIME);

-- ---------------------------------------------------------------------
-- 9) PAYMENT_RECOVERY_TASK
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_RECOVERY_TASK
(
    ID                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TARGET_TYPE          TEXT      NOT NULL,
    TARGET_TRX_NO        TEXT      NOT NULL,
    TARGET_ATTEMPT_SEQ   INTEGER   NULL,
    ORIGINAL_POS_TRX     TEXT      NOT NULL,
    ORIGINAL_ATTEMPT_SEQ INTEGER   NOT NULL,
    RECOVERY_STATUS      TEXT      NOT NULL,
    RETRY_COUNT          INTEGER   NOT NULL DEFAULT 0,
    NEXT_RETRY_AT        TIMESTAMP NULL,
    CLAIM_TOKEN          TEXT      NULL,
    LEASE_EXPIRES_AT     TIMESTAMP NULL,
    CREATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (TARGET_TYPE IN ('APPROVAL', 'CANCEL', 'REVERSAL')),
    CHECK (RECOVERY_STATUS IN ('PENDING', 'RUNNING', 'RETRY_WAIT', 'RESOLVED', 'MANUAL_REVIEW')),
    CHECK (RETRY_COUNT >= 0),
    CHECK (
        (
            TARGET_TYPE = 'APPROVAL'
            AND TARGET_ATTEMPT_SEQ IS NOT NULL
        )
        OR
        (
            TARGET_TYPE IN ('CANCEL', 'REVERSAL')
            AND TARGET_ATTEMPT_SEQ IS NULL
        )
    ),
    CHECK (
        (
            RECOVERY_STATUS = 'PENDING'
            AND NEXT_RETRY_AT IS NULL
            AND CLAIM_TOKEN IS NULL
            AND LEASE_EXPIRES_AT IS NULL
        )
        OR
        (
            RECOVERY_STATUS = 'RUNNING'
            AND NEXT_RETRY_AT IS NULL
            AND CLAIM_TOKEN IS NOT NULL
            AND LEASE_EXPIRES_AT IS NOT NULL
        )
        OR
        (
            RECOVERY_STATUS = 'RETRY_WAIT'
            AND NEXT_RETRY_AT IS NOT NULL
            AND CLAIM_TOKEN IS NULL
            AND LEASE_EXPIRES_AT IS NULL
        )
        OR
        (
            RECOVERY_STATUS IN ('RESOLVED', 'MANUAL_REVIEW')
            AND NEXT_RETRY_AT IS NULL
            AND CLAIM_TOKEN IS NULL
            AND LEASE_EXPIRES_AT IS NULL
        )
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS UK_PAYMENT_RECOVERY_TASK_APPROVAL
    ON PAYMENT_RECOVERY_TASK (TARGET_TYPE, TARGET_TRX_NO, TARGET_ATTEMPT_SEQ)
    WHERE TARGET_TYPE = 'APPROVAL';

CREATE UNIQUE INDEX IF NOT EXISTS UK_PAYMENT_RECOVERY_TASK_OPERATION
    ON PAYMENT_RECOVERY_TASK (TARGET_TYPE, TARGET_TRX_NO)
    WHERE TARGET_TYPE IN ('CANCEL', 'REVERSAL');

-- ---------------------------------------------------------------------
-- 10) PAYMENT_RECOVERY_HISTORY
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PAYMENT_RECOVERY_HISTORY
(
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECOVERY_TASK_ID BIGINT    NOT NULL,
    TRY_NO           INTEGER   NOT NULL,
    RESULT           TEXT      NULL,
    ERROR_CODE       TEXT      NULL,
    STARTED_AT       TIMESTAMP NOT NULL,
    FINISHED_AT      TIMESTAMP NULL,

    CHECK (TRY_NO > 0),

    UNIQUE (RECOVERY_TASK_ID, TRY_NO),

    FOREIGN KEY (RECOVERY_TASK_ID)
        REFERENCES PAYMENT_RECOVERY_TASK (ID)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);
