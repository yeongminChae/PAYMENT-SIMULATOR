    def test_bounds_unique_trials(self):
        for n in (10,100,500,1000):
            first=c.manifest('20261027',0,n,False); last=c.manifest('20261027',9800,n,False)
            self.assertEqual(len({f['target'] for f in first+last}),2*n)
            self.assertTrue(all(re.fullmatch(r'9376-\d{8}-\d{4}-\d{4}',f['target']) for f in last))
        for args in [('20260230',0,10,False),('20261027',9900,10,False),('20261027',0,1000,True)]:
            with self.assertRaises(ValueError): c.manifest(*args)

    def test_schema_fixtures_and_status_validation(self):
        for mixed in (False,True):
            items=c.manifest('20261027',0,10,mixed); p,v,data=fixture_data(items)
            self.assertEqual(c.validate(items,data(),True),[])
            resolved_fixture(items,p); self.assertEqual(c.validate(items,data()),[])
            for defect in ('missing','duplicate','status','ownership','identity'):
                broken=copy.deepcopy(data())
                if defect=='missing': broken['attempts'].pop(0)
                if defect=='duplicate': broken['tasks'].append(broken['tasks'][0])
                if defect=='status': broken['attempts'][0]['final_status']='DECLINED'
                if defect=='ownership': broken['tasks'][0]['claim_token']='stale-owner'
                if defect=='identity': broken['tasks'][0]['original_pos_trx']='wrong'
                self.assertTrue(c.validate(items,broken),defect)
            # 동일 대상을 다시 읽어도 검증 함수가 Task/History를 변경하지 않는다.
            original=copy.deepcopy(data()); c.validate(items,data()); self.assertEqual(data(),original)
            p.close(); v.close()

    def test_sql_missing_duplicate_wrong_status(self):
        items=c.manifest('20261027',0,10,False); p,v,data=fixture_data(items); resolved_fixture(items,p)
        p.execute('CREATE TEMP TABLE ev01_c_expected(target_type,target,original,expected_task)')
        p.executemany('INSERT INTO ev01_c_expected VALUES (?,?,?,?)',[(f['type'],f['target'],f['original'],f['expected_task']) for f in items])
        source=(c.EV/'sql/assert-recovery-backlog.sql').read_text()
        select=source.split('COPY (',1)[1].rsplit(') TO STDOUT',1)[0]
        self.assertTrue(all(r['assertion_ok'] for r in p.execute(select)))
        p.execute("UPDATE payment_recovery_task SET recovery_status='MANUAL_REVIEW' WHERE id=1")
        self.assertFalse(p.execute(select).fetchone()['assertion_ok'])
        p.execute("UPDATE payment_recovery_task SET recovery_status='RESOLVED' WHERE id=1")
        p.execute('DELETE FROM payment_recovery_history WHERE recovery_task_id=1')
        self.assertFalse(p.execute(select).fetchone()['assertion_ok'])
        p.execute('INSERT INTO payment_recovery_task SELECT 999,target_type,target_trx_no,target_attempt_seq,original_pos_trx,original_attempt_seq,recovery_status,retry_count,next_retry_at,claim_token,lease_expires_at,created_at,updated_at FROM payment_recovery_task WHERE id=1')
        self.assertEqual(p.execute(select).fetchone()['task_count'],2)
        self.assertFalse(p.execute(select).fetchone()['assertion_ok']); p.close(); v.close()

    def test_process_failure_timeout_and_summary(self):
        with tempfile.TemporaryDirectory() as root:
            failed=c.run_command([sys.executable,'-c','raise SystemExit(7)'],os.environ,Path(root)/'failed.log',5)
            self.assertEqual(failed['exit_code'],7); self.assertFalse(failed['timeout'])
            timed=c.run_command([sys.executable,'-c','import time; time.sleep(10)'],os.environ,Path(root)/'timeout.log',0.05)
            self.assertTrue(timed['timeout'])
            c.summarize(Path(root),c.manifest('20261027',0,10,False),['fixture partially committed'])
            self.assertEqual(json.loads((Path(root)/'run-summary.json').read_text())['status'],'FAIL')
        self.assertTrue(c.validate_job(dict(status='FAILED',steps=[]),c.manifest('20261027',0,10,False)))


